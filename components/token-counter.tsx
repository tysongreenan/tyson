import type { CSSProperties } from "react";
import usage from "@/content/token-usage.json";

const fullNumber = new Intl.NumberFormat("en-CA");
const compact = new Intl.NumberFormat("en-CA", { notation: "compact", maximumFractionDigits: 1 });
const date = (iso: string) =>
  new Date(`${iso}T12:00:00Z`).toLocaleDateString("en-CA", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" });

const DIGITS = "01234567890123456789".split("");

/**
 * The number as a row of digit strips that roll into place (CSS only). The strips are decorative:
 * screen readers get the plain number from the <data> element.
 */
function Odometer({ value }: { value: number }) {
  const text = fullNumber.format(value);
  let index = 0;
  return (
    <data value={value} className="odometer-wrap">
      <span className="sr-only">{text}</span>
      <span aria-hidden className="odometer">
        {text.split("").map((ch, i) =>
          /\d/.test(ch) ? (
            <span
              key={i}
              className="odometer-strip"
              // --d: the digit to land on; --i: fallback stagger index where sibling-index() isn't supported.
              style={{ "--d": Number(ch), "--i": ++index } as CSSProperties}
            >
              {DIGITS.map((d, j) => (
                <span key={j}>{d}</span>
              ))}
            </span>
          ) : (
            <span key={i} className="odometer-sep">
              {ch}
            </span>
          ),
        )}
      </span>
    </data>
  );
}

const providers = Object.keys(usage.providers)
  .join(", ")
  .replace(/, ([^,]*)$/, " and $1");

/** All-time token count from my coding agents, generated by `pnpm tokens` from T3 Code's usage cache. */
export function TokenCounter({ variant = "inline", className = "" }: { variant?: "inline" | "side"; className?: string }) {
  const id = variant === "side" ? "token-counter-side" : "token-counter";
  return (
    <section aria-labelledby={id} className={`token-card ${variant === "side" ? "token-card-side" : ""} ${className}`}>
      <h2 id={id} className="text-[0.8em] text-rurikon-400">
        Tokens through my coding agents
      </h2>
      <p className="mt-2 font-semibold text-rurikon-700 text-[1.35em]">
        <Odometer value={usage.total} />
      </p>
      <p className="mt-2 text-[0.8em] leading-snug text-rurikon-400">
        {compact.format(usage.total)} tokens across {fullNumber.format(usage.messages)} agent messages in {providers},
        since {date(usage.since)}. Most of it is context the agents re-read each step; they wrote{" "}
        {compact.format(usage.output)} tokens of output.
      </p>
      <p className="mt-1 text-[0.75em] text-rurikon-400">Updated {date(usage.asOf)}</p>
    </section>
  );
}
